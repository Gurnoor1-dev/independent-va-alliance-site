create table if not exists private.application_submission_attempts(
 id bigint generated by default as identity primary key,
 ip_hash text not null,
 attempted_at timestamptz not null default now()
);
create index if not exists application_submission_attempts_ip_time_idx on private.application_submission_attempts(ip_hash,attempted_at desc);
create or replace function public.submit_application(
 p_name text,p_kind text,p_ceo_ifc_username text,p_email text,p_experience text,
 p_operations_plan text,p_website_url text,p_website_valid boolean,p_notes text,p_human_check boolean
) returns uuid language plpgsql security definer set search_path=public,private,extensions
as $$
declare new_id uuid;headers jsonb;ip_value text;ip_digest text;attempt_count integer;
begin
 if not coalesce(p_human_check,false) then raise exception 'Human confirmation is required';end if;
 if length(trim(p_name))<2 or length(trim(p_ceo_ifc_username))<2 then raise exception 'Complete the required identity fields';end if;
 if p_kind not in('VA','VO') then raise exception 'Invalid organisation type';end if;
 if p_website_url !~* '^https?://' or not coalesce(p_website_valid,false) then raise exception 'Verify a valid website URL first';end if;
 if length(trim(p_experience))<30 or length(trim(p_operations_plan))<50 then raise exception 'Please provide a little more detail in your experience and operations plan';end if;
 headers:=coalesce(nullif(current_setting('request.headers',true),''),'{}')::jsonb;
 ip_value:=coalesce(nullif(headers->>'cf-connecting-ip',''),nullif(split_part(coalesce(headers->>'x-forwarded-for',''),',',1),''));
 if ip_value is not null then
  ip_digest:=encode(extensions.digest(trim(ip_value),'sha256'),'hex');
  select count(*) into attempt_count from private.application_submission_attempts where ip_hash=ip_digest and attempted_at>now()-interval '1 hour';
  if attempt_count>=3 then raise exception 'Application limit reached for this network. Please try again later.';end if;
  insert into private.application_submission_attempts(ip_hash) values(ip_digest);
 end if;
 insert into public.applications(name,kind,ceo_ifc_username,email,experience,operations_plan,website_url,website_valid,notes)
 values(trim(p_name),p_kind,trim(p_ceo_ifc_username),trim(p_email),trim(p_experience),trim(p_operations_plan),trim(p_website_url),true,nullif(trim(p_notes),'')) returning id into new_id;
 return new_id;
end $$;
revoke execute on function public.submit_application(text,text,text,text,text,text,text,boolean,text,boolean) from public;
grant execute on function public.submit_application(text,text,text,text,text,text,text,boolean,text,boolean) to anon,authenticated;
